//////////////////////////////////////////////////////
// REQUIRE MODULES
//////////////////////////////////////////////////////
const express = require('express');

//////////////////////////////////////////////////////
// CREATE ROUTER
//////////////////////////////////////////////////////
const router = express.Router();
const messageController = require('../controllers/messageController');
const jwtMiddleware = require('../middlewares/jwtMiddleware');

//////////////////////////////////////////////////////
// DEFINE ROUTES
//////////////////////////////////////////////////////
router.get('/', messageController.getAllMessages);
router.post('/', jwtMiddleware.verifyToken, messageController.createNewMessage);
router.put('/:messageId', jwtMiddleware.verifyToken, messageController.updateMessageById);
router.delete('/:messageId', jwtMiddleware.verifyToken, messageController.deleteMessageById);

//////////////////////////////////////////////////////
// EXPORT ROUTER
//////////////////////////////////////////////////////
module.exports = router;